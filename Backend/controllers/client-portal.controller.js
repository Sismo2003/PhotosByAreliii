const qualityOf = (req, allowed = ['web', 'original']) => {
  const q = req.query.quality ?? req.body?.quality ?? 'web';
  if (!allowed.includes(q)) throw new HttpError(400, 'quality must be web or original');
  return q;
};

// GET /galleries/:slug/photos/:photoId/download?quality=web|original — an attachment. `original` is the
// full-quality file with Areli's rights written in (camera data and GPS kept). Logging is the client's POST.
export const downloadPhoto = async (req, res) => {
  let copy = null;
  try {
    const quality = qualityOf(req);
    const [file] = await ClientPortalModel.downloadFiles(req.scope, slugParam(req), [parseId(req.params.photoId, 'photo id')], quality);
    res.set({ 'Cache-Control': 'private, no-store', 'X-Content-Type-Options': 'nosniff' });
    let target = { root: STORAGE_PATH, rel: file.rel };
    if (quality === 'original') {
      copy = await stampedOriginal(file.gallery, file.rel);
      target = { rel: copy.path };
      res.attachment(file.filename);
    } else {
      res.type('image/jpeg');
      // The web copy is always a JPEG, whatever the original was.
      res.attachment(file.filename.replace(/\.[^.]+$/, '') + '.jpg');
    }
    const done = () => copy?.cleanup();
    res.on('close', done);
    return res.sendFile(target.rel, { root: target.root, dotfiles: 'allow' }, (err) => {
      if (err && !res.headersSent) sendError(res, new HttpError(404, 'Photo not found'), 'Photo not found');
    });
  } catch (error) {
    await copy?.cleanup();
    return sendError(res, error, 'Failed to download the photo');
  }
};

// One ZIP at a time per client: it is a long stream and a stamped copy of every file.
const zipping = new Set();

// GET /galleries/:slug/download.zip?quality=original|web&(all=1 | favorites=1 | setId= | ids=1,2,3)
export const downloadZip = async (req, res) => {
  const clientId = req.scope.clientId;
  if (zipping.has(clientId)) return sendError(res, new HttpError(429, 'A download is already running. Wait for it to finish.', { code: 'ZIP_BUSY' }), 'Busy');
  zipping.add(clientId);
  try {
    const quality = qualityOf(req);
    const slug = slugParam(req);
    const pick = req.query.ids
      ? { ids: [...new Set(String(req.query.ids).split(',').map((id) => parseId(id, 'photo id')))] }
      : req.query.favorites === '1'
        ? { favorites: true }
        : req.query.setId
          ? { setId: parseId(req.query.setId, 'set id') }
          : { all: true };
    if (pick.ids && pick.ids.length > 500) throw new HttpError(400, 'Too many photos selected');
    const plan = await ClientPortalModel.zipPlan(req.scope, slug, pick, quality, req.user.id);
    await streamZip(res, { ...plan, quality, filename: `${slug}${quality === 'web' ? '-web' : ''}.zip` });
  } catch (error) {
    if (res.headersSent) res.destroy();
    else sendError(res, error, 'Failed to build the ZIP');
  } finally {
    zipping.delete(clientId);
  }
};

