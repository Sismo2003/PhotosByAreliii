// ---- Edit for the download -----------------------------------------------------------------
// GET …/photos/:id/download-edited?rotate=90&straighten=-2.5&flipH=1&flipV=1&resize=2048x1365
// Nothing is stored. Every value is checked here, so nothing free-form ever reaches sharp. A GET, so
// Areli can try it in "Preview as client" (the preview is read only).
const num = (v, name, min, max) => {
  const n = Number(v);
  if (!Number.isFinite(n) || n < min || n > max) throw new HttpError(400, `${name} must be between ${min} and ${max}`);
  return n;
};

function editOps(query) {
  const rotate = query.rotate === undefined ? 0 : num(query.rotate, 'rotate', -270, 270);
  if (rotate % 90 !== 0) throw new HttpError(400, 'rotate must be a multiple of 90');
  const straighten = query.straighten === undefined ? 0 : num(query.straighten, 'straighten', -15, 15);
  let resize = null;
  if (query.resize !== undefined) {
    const m = /^(\d{1,5})x(\d{1,5})$/.exec(String(query.resize));
    if (!m || Number(m[1]) < 1 || Number(m[2]) < 1) throw new HttpError(400, 'resize must look like 2048x1365');
    resize = { width: Number(m[1]), height: Number(m[2]) };
  }
  const ops = { rotate, straighten, flipH: query.flipH === '1', flipV: query.flipV === '1', crop: null, resize };
  if (!rotate && !straighten && !ops.flipH && !ops.flipV && !resize) throw new HttpError(400, 'Nothing to change');
  return ops;
}

// At most 2 edits running at once for the whole server, and one per client: each decodes a full original.
const MAX_EDITS = 2;
let editing = 0;
const waiting = [];
const editingClients = new Set();

async function withEditSlot(fn) {
  if (editing >= MAX_EDITS) await new Promise((resolve) => waiting.push(resolve));
  editing += 1;
  try {
    return await fn();
  } finally {
    editing -= 1;
    waiting.shift()?.();
  }
}

export const downloadEdited = async (req, res) => {
  const clientId = req.scope.clientId;
  if (editingClients.has(clientId)) return sendError(res, new HttpError(429, 'Another edit is still being prepared.', { code: 'EDIT_BUSY' }), 'Busy');
  editingClients.add(clientId);
  let copy = null;
  try {
    const ops = editOps(req.query);
    const src = await ClientPortalModel.editedSource(req.scope, slugParam(req), parseId(req.params.photoId, 'photo id'), ops);
    copy = await withEditSlot(() => editedOriginal(src.gallery, src.rel, ops));
    const ext = copy.path.split('.').pop();
    res.set({ 'Cache-Control': 'private, no-store', 'X-Content-Type-Options': 'nosniff' });
    res.attachment(`${src.filename.replace(/\.[^.]+$/, '')}-edited.${ext}`);
    res.on('close', () => copy.cleanup());
    return res.sendFile(copy.path, { dotfiles: 'allow' }, (err) => {
      if (err && !res.headersSent) sendError(res, new HttpError(404, 'Photo not found'), 'Photo not found');
    });
  } catch (error) {
    await copy?.cleanup();
    return sendError(res, error, 'Failed to prepare the edited photo');
  } finally {
    editingClients.delete(clientId);
  }
};
