// Booking codes are generated by the backend ("PBA-0151"); anything else can't be one.
function codeParam(req) {
  const code = String(req.params.code ?? '');
  if (!/^PBA-\d{1,9}$/.test(code)) throw new HttpError(404, 'Booking not found');
  return code;
}

// GET /bookings/:code/calendar.ics — "Add to calendar". A file the browser opens itself (iOS Safari
// hands it to Calendar; a blob from JS doesn't), so it also works in Preview as client.
export const bookingCalendar = async (req, res) => {
  try {
    const event = await ClientPortalModel.calendarEvent(req.scope, codeParam(req));
    res.set({
      'Cache-Control': 'private, no-store',
      'X-Content-Type-Options': 'nosniff',
      'Content-Type': 'text/calendar; charset=utf-8',
      'Content-Disposition': `attachment; filename="${event.code}.ics"`,
    });
    return res.send(toICS(event));
  } catch (error) {
    return sendError(res, error, 'Failed to build the calendar file');
  }
};

// GET /galleries/:slug/photos/:photoId/:variant — thumb | web, to look at. Downloads come later.
export const photoFile = async (req, res) => {
  try {
    const variant = req.params.variant;
    if (!['thumb', 'web'].includes(variant)) throw new HttpError(404, 'Photo not found');
    const rel = await ClientPortalModel.photoFile(req.scope, slugParam(req), parseId(req.params.photoId, 'photo id'), variant);
    // private: a shared cache (CDN, proxy) must never keep someone's photos.
    res.set({ 'Cache-Control': 'private, max-age=3600', 'X-Content-Type-Options': 'nosniff' });
    res.type('image/jpeg');
    // `root` keeps the file inside the storage folder whatever the stored path says.
    return res.sendFile(rel, { root: STORAGE_PATH, dotfiles: 'deny' }, (err) => {
      if (err && !res.headersSent) sendError(res, new HttpError(404, 'Photo not found'), 'Photo not found');
    });
  } catch (error) {
    return sendError(res, error, 'Failed to load the photo');
  }
};

